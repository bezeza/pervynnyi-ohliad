const num = s => parseFloat(String(s).replace(',', '.'));
const dec = n => String(n).replace('.', ',');
const cm = s => { const h = num(s); return isNaN(h) ? 0 : (h < 3 ? Math.round(h * 100) : h); }; // 1,72 м → 172 см

