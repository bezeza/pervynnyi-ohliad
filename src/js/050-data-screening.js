  const a = parseInt(mv('age'), 10), sm = scrSmoker(), fv = F('scr.vyk');
  box.innerHTML = '';
  if (isNaN(a)){ box.append(h('p', {class:'note'}, 'Вкажіть вік пацієнта у вкладці «Пацієнт» — тоді тут з’явиться перелік скринінгів.')); return; }
