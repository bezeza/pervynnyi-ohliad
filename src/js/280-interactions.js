/* ===== Взаємодії ліків і алергія (основні, клінічно значущі; не замінює довідника) ===== */
const DCLS = {
  ac:['Ривароксабан','Апіксабан','Дабігатран','Еноксапарин','Гепарин'],
  doac:['Ривароксабан','Апіксабан','Дабігатран'],
  apl:['Ацетилсаліцилова кислота','Клопідогрель'],
  nsaid:['Ібупрофен','Диклофенак','Кеторолак'],
  qt:['Кларитроміцин','Азитроміцин','Левофлоксацин','Моксифлоксацин','Ципрофлоксацин','Аміодарон','Метоклопрамід'],
  raas:['Раміприл','Лізиноприл','Периндоприл','Валсартан'],
  ksp:['Спіронолактон'],
  diur:['Фуросемід','Торасемід','Індапамід','Гідрохлортіазид'],
  gcs:['Преднізолон','Дексаметазон'],
  bb:['Бісопролол','Метопрололу сукцинат'],
  ppi:['Пантопразол','Омепразол'],
  pen:['Амоксицилін','Амоксицилін/клавуланат','Ампіцилін/сульбактам','Бензилпеніцилін','Піперацилін/тазобактам'],
  ceph:['Цефазолін','Цефтріаксон','Цефотаксим','Цефуроксим'],
  fq:['Левофлоксацин','Ципрофлоксацин','Моксифлоксацин'],
  macro:['Кларитроміцин','Азитроміцин'],
  sulf:['Ко-тримоксазол']
};
const inC = (list, c) => list.filter(d=>DCLS[c].includes(d));
function rxWarnings(){
  const d = todayISO(), act = RXF().filter(it=>!it.stop || it.stop > d).map(it=>it.drug), W = [];
  const ac = inC(act, 'ac'), ns = inC(act, 'nsaid'), apl = inC(act, 'apl'), qt = inC(act, 'qt'), raas = inC(act, 'raas'), ksp = inC(act, 'ksp'), diur = inC(act, 'diur'), gcs = inC(act, 'gcs');
  if (ac.length > 1) W.push({c:'bad', t:`Два антикоагулянти одночасно (${ac.join(', ')}) — перевірте, чи це не дублювання (напр. профілактична доза + ПОАК).`});
  if (ac.length && ns.length) W.push({c:'bad', t:`Антикоагулянт + НПЗП (${[...ac, ...ns].join(', ')}): високий ризик кровотечі. Розгляньте парацетамол.`});
  if (ac.length && apl.length) W.push({c:'warn', t:`Антикоагулянт + антиагрегант (${[...ac, ...apl].join(', ')}): ризик кровотечі — лише за чітких показань, гастропротекція.`});
  if (ns.length > 1) W.push({c:'bad', t:`Два НПЗП одночасно (${ns.join(', ')}) — не поєднувати.`});
  if (ns.length && apl.includes('Ацетилсаліцилова кислота')) W.push({c:'warn', t:'НПЗП + ацетилсаліцилова кислота: ризик кровотечі зі ШКТ; ібупрофен може знижувати антиагрегантний ефект.'});
  if ((ns.length || ac.length) && gcs.length && !inC(act, 'ppi').length) W.push({c:'warn', t:'ГКС разом із НПЗП або антикоагулянтом без ІПП — розгляньте гастропротекцію.'});
  if (qt.length > 1) W.push({c:'warn', t:`Кілька препаратів, що подовжують QT (${qt.join(', ')}) — ЕКГ-контроль QTc, калій і магній.`});
  if (raas.length && ksp.length) W.push({c:'warn', t:`іАПФ/БРА + спіронолактон: ризик гіперкаліємії — контроль калію і креатиніну.`});
  if (raas.length > 1) W.push({c:'bad', t:`Два блокатори РААС (${raas.join(', ')}) — не поєднувати.`});
  if (ns.length && raas.length && diur.length) W.push({c:'bad', t:'НПЗП + іАПФ/БРА + діуретик («потрійний удар»): ризик гострого ураження нирок.'});
  if (act.includes('Кларитроміцин') && act.includes('Аторвастатин')) W.push({c:'warn', t:'Кларитроміцин + аторвастатин: ризик міопатії — призупиніть статин на час курсу або оберіть азитроміцин.'});
  if (act.includes('Кларитроміцин') && inC(act, 'doac').length) W.push({c:'warn', t:'Кларитроміцин підвищує концентрацію ПОАК — ризик кровотечі.'});
  if (act.includes('Аміодарон') && act.includes('Дигоксин')) W.push({c:'warn', t:'Аміодарон + дигоксин: дозу дигоксину зменшити приблизно вдвічі, контроль ЧСС.'});
  if ((act.includes('Аміодарон') || act.includes('Дигоксин')) && inC(act, 'bb').length) W.push({c:'warn', t:'Бета-блокатор з аміодароном чи дигоксином: ризик брадикардії — контроль ЧСС.'});
  const K = num(((document.getElementById('ctrl_k_0') || {}).value || '')) ; const kRes = RES.slice().reverse().map(r=>/калій\s+([\d,.]+)/i.exec(r.v)).find(Boolean);
  const kv = kRes ? num(kRes[1]) : K;
  if (!isNaN(kv) && kv > 5 && (raas.length || ksp.length)) W.push({c:'bad', t:`Калій ${dec(kv)} ммоль/л на тлі іАПФ/БРА чи спіронолактону — перегляньте дози.`});
  // алергія
  const al = (val(F('vitae.alerg'), true) + ' ' + val(F('vitae.alergx'), true)).toLowerCase();
  if (al.trim() && !/не обтяжений/.test(al) || /пеніцилін|нпзп/.test(al)){
    const hit = (re, cls, msg) => { if (re.test(al)){ const x = inC(act, cls); if (x.length) W.push({c:'bad', t:`Алергія в анамнезі (${msg}): ${x.join(', ')}!`}); } };
    hit(/пеніцилін|амоксицилін|ампіцилін/, 'pen', 'пеніциліни');
    if (/пеніцилін/.test(al)){ const x = inC(act, 'ceph'); if (x.length) W.push({c:'warn', t:`Алергія на пеніциліни: перехресна реакція з цефалоспоринами (${x.join(', ')}) можлива — уточніть тип реакції.`}); }
    hit(/цефал|цефтріакс|цефазол/, 'ceph', 'цефалоспорини');
    hit(/нпзп|ібупрофен|диклофенак|кеторолак|аспірин|ацетилсаліц/, 'nsaid', 'НПЗП');
    if (/нпзп|аспірин|ацетилсаліц/.test(al) && act.includes('Ацетилсаліцилова кислота')) W.push({c:'bad', t:'Алергія в анамнезі (НПЗП/аспірин): ацетилсаліцилова кислота!'});
    hit(/фторхінол|ципро|левоф|моксиф/, 'fq', 'фторхінолони');
    hit(/макролід|кларитром|азитром/, 'macro', 'макроліди');
    hit(/сульфан|бісептол|ко-тримокс/, 'sulf', 'сульфаніламіди');
    act.forEach(dn=>{ const w = dn.toLowerCase().split(/[\/ ]/)[0]; if (w.length > 4 && al.includes(w.slice(0, 6)) && !W.some(x=>x.t.includes(dn))) W.push({c:'bad', t:`В анамнезі алергія на «${dn}»!`}); });
  }
  return W;
}

